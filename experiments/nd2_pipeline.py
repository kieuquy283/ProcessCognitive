from sklearn.metrics import accuracy_score, f1_score, cohen_kappa_score, precision_recall_fscore_support, confusion_matrix

ACT=['AK','AN','CQ','HR','OT','RE','VE']; UPT=['AC','AP','NO','NR','UN']; CONF=['high','medium','low']
INPUT=['episode_id','previous_student_excerpt','tutor_context','student_turn']
COLUMNS=INPUT+['primary_act','feedback_uptake','annotation_rationale','confidence']
SEED=27102026
SOURCE_REVISION='304c8d63c726e72b60510bba3a44454fc0726721'

def wilson(success,total,z=1.959963984540054):
    """Binomial Wilson interval; conditional on the sampled reference labels."""
    if not total:return [None,None]
    p=success/total
    den=1+z*z/total
    center=(p+z*z/(2*total))/den
    margin=z*math.sqrt(p*(1-p)/total+z*z/(4*total*total))/den
    return [max(0,center-margin),min(1,center+margin)]

def digest(x): return hashlib.sha256(str(x).encode('utf-8')).hexdigest()
def sha(path):
    h=hashlib.sha256()
    with open(path,'rb') as f:
        for block in iter(lambda:f.read(1<<20),b''):h.update(block)
    return h.hexdigest()
def getcsv(p):
    with open(p,encoding='utf-8-sig',newline='') as f:return list(csv.DictReader(f))

def discover(root):
    root=Path(root); result=[]
    for section in ('gre_quant','gre_verbal'):
        base=root/'1_main_leaderboard_data'/section
        if not base.is_dir():continue
        for path in sorted(base.glob('ai_arm_*/task_id_*/ai_tutoring_data/student_ai_tutor_interaction_trajectory.csv')):
            rows=getcsv(path)
            required={'event_type','trajectory_position','content'}
            if not rows or not required.issubset(rows[0]):raise ValueError(f'Missing required fields: {path}')
            events=sorted(rows,key=lambda x:int(x['trajectory_position']))
            sid=f'{section}/{path.parent.parent.parent.name}/{path.parent.parent.name}'
            result.append((sid,section,path.parent.parent.parent.name,events))
    if not result:raise FileNotFoundError('No official GRE Quant/Verbal AI trajectory CSV files found under --data; download the official dataset first')
    return result

def build(root,nd1_ids):
    out=[]; nd1=set(nd1_ids)
    for sid,section,arm,events in discover(root):
        prev_student=''; since_student=[]; turn=0
        for ev in events:
            typ=ev['event_type']; content=ev.get('content','').strip()
            if typ=='student_message' and content:
                turn+=1; eid='ND2-'+digest(f'{sid}/{ev["trajectory_position"]}')[:20]
                if eid not in nd1:
                    # Preserve complete tutor responses since previous student turn.
                    tutor='\n\n'.join(since_student)
                    out.append({'episode_id':eid,'previous_student_excerpt':prev_student,
                                'tutor_context':tutor,'student_turn':content,
                                'session_key':digest(sid)[:20],'section':section,'tutor_configuration':arm,
                                'turn_index':turn,'source_position':ev['trajectory_position'],
                                'context_truncated':'false'})
                prev_student=content; since_student=[]
            elif typ=='ai_tutor_message' and content: since_student.append(content)
    return out

def load_nd1_sessions(path, nd1):
    """Validate an externally supplied *private* ND1 episode-to-session map.

    This establishes file completeness, NOT independently verified provenance.
    Session keys must be generated by the same SHA-256 method as this script.
    """
    mappings=getcsv(path)
    needed={'episode_id','session_key'}
    if not mappings or not needed.issubset(mappings[0]):
        raise ValueError('ND1 source mapping requires nonempty episode_id and session_key columns')
    ids=[x['episode_id'] for x in mappings]
    if len(ids)!=len(set(ids)) or set(ids)!={x['episode_id'] for x in nd1}:
        raise ValueError('ND1 source mapping must contain exactly all ND1 episode IDs, once each')
    keys=[]
    for row in mappings:
        key=row['session_key'].strip()
        if not re.fullmatch(r'[0-9a-f]{20}',key):
            raise ValueError('ND1 session_key must be a 20-character SHA-256 hex prefix')
        keys.append(key)
    return set(keys)

def source_revision_audit(root):
    """Read a locally recorded snapshot revision, without making network claims."""
    stamp=Path(root)/'.studentbench_revision'
    if not stamp.is_file():
        return {'revision_record_found':False, 'revision_record_matches_expected':False}
    actual=stamp.read_text(encoding='utf-8').strip()
    if not re.fullmatch(r'[0-9a-f]{40}', actual):
        raise ValueError('Invalid source .studentbench_revision stamp')
    if actual!=SOURCE_REVISION:
        raise ValueError('Source snapshot revision differs from pinned ND2 protocol')
    return {'revision_record_found':True,'revision_record_matches_expected':True}

def verify_attested_nd1_mapping(nd1_file,mapping_file,attestation_file):
    """Document independent source review; no attestation may be fabricated."""
    if not attestation_file:return False
    if not mapping_file:raise ValueError('Cannot attest ND1 provenance without --nd1-sessions')
    obj=json.loads(Path(attestation_file).read_text(encoding='utf-8'))
    if obj.get('source_revision')!=SOURCE_REVISION:
        raise ValueError('ND1 attestation source revision mismatch')
    if obj.get('nd1_sha256')!=sha(nd1_file) or obj.get('mapping_sha256')!=sha(mapping_file):
        raise ValueError('ND1 attestation SHA mismatch; re-review changed source or mapping')
    if not (obj.get('reviewed_by') and obj.get('reviewed_at') and
            obj.get('mapping_decision')=='approved' and obj.get('all_40_verified') is True):
        raise ValueError('ND1 mapping independent review approval is missing')
    return True

def make(args):
    nd1=getcsv(args.nd1); old={x['episode_id'] for x in nd1}
    if len(old)!=len(nd1) or not old:raise ValueError('Empty or duplicate ND1 IDs')
    source_audit=source_revision_audit(args.data)
    rows=build(args.data,old)
    if len(rows)<280:raise ValueError(f'Only {len(rows)} eligible turns; need at least 280')
    by_session=defaultdict(list)
    for row in rows:by_session[row['session_key']].append(row)
    # Sample one turn per session to prevent within-ND2 clustering; ensure ND2 is
    # strictly session-disjoint from ND1 only where ND1 session mapping is known.
    forbidden=load_nd1_sessions(args.nd1_sessions,nd1) if args.nd1_sessions else set()
    map_reviewed=verify_attested_nd1_mapping(args.nd1,args.nd1_sessions,args.provenance_attestation)
    for k in forbidden:by_session.pop(k,None)
    if len(by_session)<280:raise ValueError(f'{len(by_session)} sessions available; need 280 disjoint sessions. No turn-level fallback permitted.')
    rnd=random.Random(args.seed)
    pool=[rnd.choice(z) for _,z in sorted(by_session.items())]
    rnd.shuffle(pool)
    # Random set is selected before challenge; challenge uses observable, label-free
    # lexical cues (not preassigned predicted labels). Challenge is NOT representative.
    natural=pool[:200]; rest=pool[200:]
    challenge=[]; categories=[
        ('coordination',r'\b(next|start|stop|skip|continue|step|explain|again|move on)\b'),
        ('reason_verify',r'\b(because|why|reason|check|verify|correct|right|prove)\b'),
        ('help_clarify',r'\b(help|hint|confused|what|how|clarify|understand)\b'),
        ('feedback',r'\b(ok|got it|thanks|actually|but|no|yes|understood|wrong)\b')]
    remaining={x['episode_id']:x for x in rest}; audit=[]
    for bucket,pattern in categories:
        matches=[x for x in remaining.values() if re.search(pattern,x['student_turn'],re.I)]
        rnd.shuffle(matches)
        if len(matches)<20:raise ValueError(f'Challenge bucket {bucket}: only {len(matches)} qualifying independent sessions (<20); do not fill with invented items')
        for x in matches[:20]:
            y=dict(x);y['split']='challenge';y['sampling_reason']=bucket;challenge.append(y);remaining.pop(x['episode_id'])
        audit.append({'bucket':bucket,'candidates':len(matches),'chosen':20,'pattern':pattern})
    for x in natural:x['split']='random';x['sampling_reason']='uniform_session_random'
    allrows=natural+challenge
    assert len(allrows)==280 and len({x['session_key'] for x in allrows})==280
    out=Path(args.outdir);out.mkdir(parents=True,exist_ok=True)
    private=pd.DataFrame(allrows)
    private.to_csv(out/'ND2_input_private.csv',index=False,encoding='utf-8')
    for name in ('Astra','Claude'):
        blinded=private[INPUT].copy()
        for col in COLUMNS[4:]:blinded[col]=''
        blinded.to_csv(out/f'ND2_{name}_blinded_private.csv',index=False,encoding='utf-8')
    # Metadata manifest is also PRIVATE: row-level IDs/session correlations.
    manifest=private[['episode_id','session_key','section','tutor_configuration','turn_index','split','sampling_reason','context_truncated']]
    manifest.to_csv(out/'ND2_manifest_private.csv',index=False)
    details={'seed':args.seed,'sample_count':280,'random':200,'challenge':80,
             'sessions_disjoint_within_nd2':True,
             'nd1_mapping_completeness_validated':bool(args.nd1_sessions),
             'nd1_session_overlap_verified':bool(args.nd1_sessions),
             'nd1_mapping_provenance_independently_verified':map_reviewed,
             'source_revision_audit':source_audit,
             'warning':('Private ND1 mapping supplied and schema/coverage validated; source-session attribution still requires independent provenance review.' if args.nd1_sessions else 'ND1 IDs are pseudonymous and cannot be mapped to source session here: no certified ND1 session-disjoint evaluation until ND1 mapping verified.'),
             'eligible_sessions':len(by_session),'source_data_path':str(Path(args.data).resolve()),
             'challenge_audit':audit,'nd1_file_sha256':sha(args.nd1),'expected_studentbench_revision':SOURCE_REVISION}
    (out/'ND2_sampling_audit_private.json').write_text(json.dumps(details,indent=2),encoding='utf-8')
    print(json.dumps({k:v for k,v in details.items() if k not in ('source_data_path','nd1_file_sha256')},indent=2))

def check(ref,pred,source):
    files=[pd.read_csv(p,dtype=str,keep_default_na=False,encoding='utf-8-sig') for p in (ref,pred,source)]
    a,b,s=files
    if len(a)!=280 or len(b)!=280 or len(s)!=280:raise ValueError('Expected 280 rows in each file')
    if a.columns.tolist()!=COLUMNS or b.columns.tolist()!=COLUMNS:raise ValueError('Unexpected annotation CSV schema')
    for d in (a,b,s):
        if not d.episode_id.is_unique:raise ValueError('Duplicate episode IDs')
    if not a.episode_id.equals(b.episode_id) or not a.episode_id.equals(s.episode_id):raise ValueError('Episode order/IDs do not match')
    for col in INPUT:
        if not a[col].equals(b[col]) or not a[col].equals(s[col]):raise ValueError(f'Immutable input mismatch: {col}')
    for d in (a,b):
        for col,labels in [('primary_act',ACT),('feedback_uptake',UPT),('confidence',CONF)]:
            if not d[col].isin(labels).all():raise ValueError(f'Invalid/missing {col}')
        if d['annotation_rationale'].str.strip().eq('').any():raise ValueError('Empty rationale')
    return a,b,s

def evaluate(args):
    a,b,s=check(args.astra,args.claude,args.source)
    manifest=pd.read_csv(args.manifest,dtype=str,keep_default_na=False)
    if not manifest.episode_id.equals(a.episode_id):raise ValueError('Manifest ID mismatch')
    if set(manifest['split'])!={'random','challenge'} or sum(manifest['split']=='random')!=200 or sum(manifest['split']=='challenge')!=80:raise ValueError('Bad split counts')
    if not manifest.session_key.is_unique:raise ValueError('Expected independent sessions')
    results={}
    for split in ('random','challenge'):
        m=(manifest['split']==split).to_numpy(); aa=a.loc[m]; bb=b.loc[m]
        x={'n':len(aa),'joint_accuracy':float(((aa.primary_act==bb.primary_act)&(aa.feedback_uptake==bb.feedback_uptake)).mean())}
        for name,labels in [('primary_act',ACT),('feedback_uptake',UPT)]:
            true=aa[name];pred=bb[name];observed=[k for k in labels if (true==k).any()]
            pr,rc,f1,support=precision_recall_fscore_support(true,pred,labels=labels,zero_division=0)
            x[name]={'accuracy':accuracy_score(true,pred), 'macro_f1_observed_labels':f1_score(true,pred,labels=observed,average='macro',zero_division=0),'kappa':float(cohen_kappa_score(true,pred)),
                     'per_class':{l:{'support':int(support[i]),'precision':float(pr[i]),'recall':float(rc[i]),'f1':float(f1[i])} for i,l in enumerate(labels)},
                     'confusion':confusion_matrix(true,pred,labels=labels).tolist(), 'accuracy_wilson95':wilson(int((true==pred).sum()),len(true)), 'observed_label_support':{l:int((true==l).sum()) for l in labels}}
        x['joint_accuracy_wilson95']=wilson(int((((aa.primary_act==bb.primary_act)&(aa.feedback_uptake==bb.feedback_uptake)).sum())),len(aa))
        x['confidence_breakdown']={c:{'n':int(sum(bb.confidence==c)),'joint_accuracy':(float((((aa.primary_act==bb.primary_act)&(aa.feedback_uptake==bb.feedback_uptake))[bb.confidence==c]).mean()) if any(bb.confidence==c) else None)} for c in CONF}
        x['by_domain']={}
        for section in sorted(manifest.loc[m,'section'].unique()):
            sub=(manifest.loc[m,'section']==section).to_numpy()
            zaa=aa.iloc[sub]; zbb=bb.iloc[sub]
            x['by_domain'][section]={'n':len(zaa), 'primary_accuracy':float((zaa.primary_act==zbb.primary_act).mean()),
              'uptake_accuracy':float((zaa.feedback_uptake==zbb.feedback_uptake).mean()),
              'joint_accuracy':float(((zaa.primary_act==zbb.primary_act)&(zaa.feedback_uptake==zbb.feedback_uptake)).mean())}
        results[split]=x
    results['source_audit']={'astra_sha256':sha(args.astra),'claude_sha256':sha(args.claude),'manifest_sha256':sha(args.manifest),'reference':'Astra convention; not independently validated ground truth','primary_outcome':'random split primary_act accuracy', 'intervals':'Wilson 95%, descriptive only', 'representativeness':'one random student turn per session'}
    # Session provenance is not recoverable from ND1 pseudonymous episode IDs.
    audit=Path(args.manifest).with_name('ND2_sampling_audit_private.json')
    if audit.is_file():
        meta=json.loads(audit.read_text(encoding='utf-8'))
        results['source_audit']['nd1_session_overlap_verified']=bool(meta.get('nd1_session_overlap_verified',False))
        results['source_audit']['source_revision_verified_by_local_stamp']=bool(meta.get('source_revision_audit',{}).get('revision_record_matches_expected',False))
        results['source_audit']['nd1_mapping_provenance_independently_verified']=bool(meta.get('nd1_mapping_provenance_independently_verified',False))
    else:
        results['source_audit']['nd1_session_overlap_verified']=False
        results['source_audit']['source_revision_verified_by_local_stamp']=False
        results['source_audit']['nd1_mapping_provenance_independently_verified']=False
    p=Path(args.outdir);p.mkdir(parents=True,exist_ok=True)
    (p/'ND2_metrics_private.json').write_text(json.dumps(results,ensure_ascii=False,indent=2),encoding='utf-8')
    r=results['random']; thresholds={'primary_accuracy':r['primary_act']['accuracy']>=.80,'primary_macro_f1':r['primary_act']['macro_f1_observed_labels']>=.75,'uptake_accuracy':r['feedback_uptake']['accuracy']>=.90,'joint_accuracy':r['joint_accuracy']>=.75}
    print(json.dumps({'random_n':r['n'],'random_metrics':{k:round(v,4) for k,v in [('primary_accuracy',r['primary_act']['accuracy']),('primary_macro_f1',r['primary_act']['macro_f1_observed_labels']),('uptake_accuracy',r['feedback_uptake']['accuracy']),('joint_accuracy',r['joint_accuracy'])]},'threshold_checks':thresholds,'provisional_outcome':('ND1 source provenance or pinned dataset record not fully verified; result is DEVELOPMENT ONLY' if not (results['source_audit']['nd1_session_overlap_verified'] and results['source_audit']['source_revision_verified_by_local_stamp'] and results['source_audit']['nd1_mapping_provenance_independently_verified']) else ('Candidate thresholds met, still subject to class support and construct validation' if all(thresholds.values()) else 'REVISE/RECONSIDER required'))},indent=2))

def main():
    p=argparse.ArgumentParser(description=__doc__);sub=p.add_subparsers(dest='command',required=True)
    q=sub.add_parser('sample');q.add_argument('--data',required=True);q.add_argument('--nd1',required=True);q.add_argument('--nd1-sessions',help='Optional private ND1 source session mapping with session_key column');q.add_argument('--provenance-attestation',help='Independent 40-case ND1 mapping review metadata; required before claiming confirmatory holdout');q.add_argument('--outdir',default='annotation_work/nd2');q.add_argument('--seed',type=int,default=SEED)
    q=sub.add_parser('evaluate');q.add_argument('--astra',required=True);q.add_argument('--claude',required=True);q.add_argument('--source',required=True);q.add_argument('--manifest',required=True);q.add_argument('--outdir',default='annotation_work/nd2')
    args=p.parse_args();(make if args.command=='sample' else evaluate)(args)
if __name__=='__main__':main()
