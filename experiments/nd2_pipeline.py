"""ND2 sampling, blinded export, input validation and reference evaluation.

Local-only inputs/outputs: DO NOT commit participant/session rows or transcripts.
Run with a downloaded, pinned official StudentBench dataset. Python 3.10+;
requirements: pandas numpy scikit-learn. No model calls and no invented labels.
"""
